/**
 * Проверка формы профиля: вес в ней только показывается.
 *
 *   pnpm tsx scripts/check-profile-form.ts [путь к ProfilePage.tsx]
 *
 * Баг 2 октября 2026: у формы была своя копия веса. Взвешивание с умных
 * весов обновляло профиль, копия оставалась старой, форма считала себя
 * изменённой и показывала «Есть несохранённые изменения». Нажатие
 * «Сохранить» писало в журнал СТАРЫЙ вес без состава тела - и только
 * что внесённые жир, мышцы, вода и базовый обмен пропадали.
 *
 * Поведение интерфейса здесь не проверить - тестов компонентов в проекте
 * нет, - поэтому проверяется исходник, как в check-i18n: форма не должна
 * снова завести свою копию веса и не должна писать журнал веса.
 * Путь аргументом - чтобы убедиться, что на старой версии проверка падает.
 */
import { readFileSync } from 'node:fs'

let failed = 0

function check(ok: boolean, name: string, detail: string): void {
  if (!ok) failed++
  console.log(`${ok ? '  OK  ' : ' ПРОВАЛ '} ${name}\n         ${detail}`)
}

const path = process.argv[2] ?? 'src/features/profile/ProfilePage.tsx'
const source = readFileSync(path, 'utf8')
// Комментарии вырезаем: в них имена встречаются, когда объясняют, почему так нельзя
const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')

check(
  !/useLogWeight/.test(code),
  'Форма профиля не пишет журнал веса',
  'вес и состав тела записывает только взвешивание - иначе форма затирает состав',
)
check(
  !/\[\s*weightKg\s*,\s*setWeightKg\s*\]\s*=\s*useState/.test(code),
  'У формы нет своей копии веса',
  'копия устаревает после взвешивания и делает форму «изменённой»',
)
const dirty = /const dirty =([\s\S]*?)\n\n/.exec(code)?.[1] ?? ''
check(
  dirty !== '' && !/weightKg/.test(dirty),
  'Вес не делает форму изменённой',
  dirty === '' ? 'не нашёл вычисление dirty' : 'в dirty веса нет',
)

console.log(failed === 0 ? '\nФорма профиля верна.' : `\nПровалено: ${failed}`)
if (failed > 0) process.exit(1)

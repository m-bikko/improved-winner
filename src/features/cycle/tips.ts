/** Подсказки для конкретных дней — они важнее фазовых и идут первыми. */
function specific(state: CycleDay): Tip[] {
  const out: Tip[] = []

  if (state.day === 1) {
    out.push({
      id: 'day-one',
      title: 'День первый — точка отсчёта',
      body: 'От него считается весь цикл и все прогнозы. Чем аккуратнее отмечена эта дата, тем ближе к правде всё остальное.',
    })
  }

  if (state.phase === 'luteal' && state.daysToNext >= 0 && state.daysToNext <= 2) {
    out.push({
      id: 'almost',
      title:
        state.daysToNext === 0
          ? 'Менструация ожидается сегодня'
          : `Менструация ожидается через ${state.daysToNext === 1 ? 'день' : '2 дня'}`,
      body: 'Прогноз по среднему, а не по календарю на стене: сдвиг на пару дней — обычное дело. Когда начнётся, отметьте — среднее станет точнее.',
    })
  }

  if (state.daysToNext < 0) {
    out.push({
      id: 'delay',
      title: `Задержка ${-state.daysToNext} дн.`,
      body: 'Стресс, болезнь, перелёт, резкая смена нагрузок или веса сдвигают цикл. Если тянется — тест и врач, в таком порядке.',
    })
  }

  return out
}

export function tipsFor(state: CycleDay): Tip[] {
  return [...specific(state), ...BY_PHASE[state.phase]]
}


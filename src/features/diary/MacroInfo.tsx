export function MacroInfoSheet({
  nutrient,
  goalDirection,
  onClose,
}: {
  nutrient: Nutrient | null
  goalDirection: GoalDirection
  onClose: () => void
}) {
  const article = nutrient ? ARTICLES[nutrient] : null

  return (
    <Sheet open={article !== null} onClose={onClose} title={article?.title ?? ''}>
      {article && (
        <div className="flex flex-col gap-4 px-4 py-4">
          <Block label="За что отвечает">{article.role}</Block>
          <Block label="Если недобирать">{article.under}</Block>
          <Block label="Если перебирать">{article.over}</Block>

          <div className="rounded-xl bg-raised px-4 py-3">
            <p className="mb-1 text-sm font-medium text-accent">Для твоей цели</p>
            <p className="text-sm">{article.forGoal[goalDirection]}</p>
          </div>

          <p className="text-xs text-muted">
            Это подсказка к трекеру, а не медицинская рекомендация. При заболеваниях
            и особых состояниях нормы считает врач.
          </p>
        </div>
      )}
    </Sheet>
  )
}

function Block({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div>
      <p className="mb-1 text-sm font-medium text-muted">{label}</p>
      <p className="text-sm leading-relaxed">{children}</p>
    </div>
  )
}

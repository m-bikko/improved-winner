/**
 * Название приложения - одно место на весь клиент.
 *
 * Задаётся при сборке через VITE_PUBLIC_APP_NAME. Именно при сборке, а не
 * в рантайме, и это не лень: iOS запоминает имя и иконку в момент добавления
 * на экран «Домой» и больше их не перечитывает. Переключатель в профиле менял
 * бы надпись внутри приложения, а подпись под иконкой осталась бы старой -
 * хуже, чем отсутствие переключателя.
 *
 * Смена названия: правим переменную, пересобираем, а на телефоне удаляем
 * и добавляем иконку заново. Это описано в README, чтобы не выяснять заново.
 *
 * Ключи localStorage и адреса аккаунтов от названия НЕ зависят
 * (`love-promises-auth`, `bikosh@lovepromises.app` и т.п.): это опознаватели
 * живых данных, и переименование не должно разлогинивать людей и терять
 * очередь неотправленных записей.
 */
export const APP_NAME: string = import.meta.env.VITE_PUBLIC_APP_NAME || 'Тандем'

/** Подпись под иконкой на домашнем экране: длинное имя там обрезается. */
export const APP_SHORT_NAME: string =
  import.meta.env.VITE_PUBLIC_APP_SHORT_NAME || APP_NAME

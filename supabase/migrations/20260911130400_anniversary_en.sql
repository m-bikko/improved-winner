-- «2th anniversary» - неверная английская форма.
--
-- Порядковые в английском требуют st/nd/rd/th по остатку, и правило это
-- в plpgsql пришлось бы писать руками ради одной строки. Вместо этого
-- формулировка меняется на ту, где порядкового просто нет: «2 years
-- together» говорит ровно то же и на любом числе верна.
--
-- В интерфейсе сделано так же, чтобы в уведомлении и на экране стояло
-- одно и то же.

update public.texts
   set value = '%1$s years together'
 where key = 'n.occasion.anniversary' and lang = 'en';

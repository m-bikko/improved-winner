-- Убираем notified_at.
--
-- Колонка появилась, когда у задачи было одно уведомление на срок. С приходом
-- настраиваемых напоминаний дедупликация целиком переехала в reminded_offsets,
-- и notify_due_tasks больше её не читает и не пишет.
--
-- Оставлять мёртвое состояние, которое выглядит живым, хуже, чем не иметь его
-- вовсе: следующий, кто откроет схему, потратит время на выяснение, почему
-- сброс notified_at ничего не меняет. Ровно это и случилось на проверке.

alter table public.tasks drop column notified_at;

-- Индекс ссылался на снятую колонку и пересоздаётся по актуальному условию:
-- планировщику нужны незакрытые задачи со сроком
drop index if exists public.tasks_due_idx;

create index tasks_due_idx on public.tasks (due_at)
  where done_at is null and due_at is not null;

-- Наши договорённости.
--
-- Решение закрытой темы - это договорённость: «деньги на крупное обсуждаем
-- заранее», «гости - не чаще раза в месяц». Сейчас каждое такое решение
-- лежит в своей теме, и через полгода его не найти. Страница договорённостей
-- собирает их вместе; важные можно закрепить сверху.
--
-- Отдельной таблицы нет: договорённость и есть закрытая тема с текстом
-- решения - инвариант topics_status_consistent уже держит, что текст есть.

alter table public.topics add column if not exists pinned_at timestamptz;

-- Закрепить можно только решённое: у открытой темы договорённости ещё нет
alter table public.topics
  add constraint topics_pin_closed check (pinned_at is null or status = 'closed');

comment on column public.topics.pinned_at is
  'Договорённость закреплена наверху страницы договорённостей.';

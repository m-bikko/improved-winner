-- Последний известный состав - в профиль.
--
-- Цели считаются функцией от одного профиля: `goalsFor(profile)` вызывается
-- из десятка мест, и ни у одного из них нет под рукой журнала веса. Тот же
-- вопрос уже решался для веса - `profiles.weight_kg` это «последнее известное
-- значение», денормализованное из `weight_log` ровно затем, чтобы расчёт
-- не тащил за собой историю.
--
-- Здесь хранится ПРОЦЕНТ жира, а не килограммы тощей массы, и это важно.
-- Процент меняется медленно - за неделю на десятые доли; вес меняется каждый
-- день. Храня процент, мы получаем тощую массу умножением на сегодняшний вес,
-- и она следует за весом сама. Храня килограммы, мы получили бы число,
-- застывшее на дне последнего взвешивания на умных весах.
--
-- Обычное взвешивание эти поля НЕ обнуляет. Состав - это свойство тела,
-- известное с последнего измерения, а не свойство сегодняшнего дня; человек,
-- взвесившийся в гостях на чужих весах, не должен из-за этого получить другую
-- норму белка.

alter table public.profiles
  add column if not exists body_fat_pct numeric(4, 1),
  add column if not exists bmr_kcal int;

alter table public.profiles
  add constraint profiles_fat_range check (body_fat_pct is null or body_fat_pct between 2 and 75),
  add constraint profiles_bmr_range check (bmr_kcal is null or bmr_kcal between 500 and 5000);

comment on column public.profiles.body_fat_pct is
  'Последний известный процент жира. Источник - weight_log, обновляется взвешиванием.';
comment on column public.profiles.bmr_kcal is
  'Базовый обмен, измеренный весами. Когда есть, заменяет формулу Миффлина.';

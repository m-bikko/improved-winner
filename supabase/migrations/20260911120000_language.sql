-- Язык интерфейса.
--
-- В профиле, а не только в localStorage: у каждого из двоих он свой,
-- переезжает вместе с аккаунтом на другое устройство, и - главное - его
-- сможет спросить база, когда дело дойдёт до языка уведомлений. Рассылки
-- собираются в plpgsql, и без этой колонки они навсегда остались бы русскими.
--
-- Умолчание русский: приложение писалось на нём, и для двоих, говорящих
-- по-русски, смена языка - действие, а не исходное состояние.

alter table public.profiles
  add column language text not null default 'ru' check (language in ('ru', 'kk', 'en'));

comment on column public.profiles.language is
  'Язык интерфейса: ru, kk или en. Его же спрашивают рассылки.';

-- Казахский текст паузы без падежа после времени.
--
-- «%2$s дейін» требовал дательного падежа у числа («19:40-қа дейін»),
-- а окончание зависит от того, как число читается. Строку перестроили так,
-- чтобы время стояло без окончания, - как и на экране паузы.

insert into public.texts (key, lang, value) values
  ('n.pause.asked', 'kk', '%1$s: үзіліс керек, аяқталуы %2$s')
on conflict (key, lang) do update set value = excluded.value;

-- Поправка к предыдущей миграции: запечатанное письмо изменить НЕЛЬЗЯ вовсе.
--
-- Там написано, что права на правку сохранены и письмо остаётся отзываемым
-- запросом к базе. Это неверно, и проверка это поймала.
--
-- В Postgres UPDATE и DELETE с условием WHERE требуют ещё и прав на ЧТЕНИЕ:
-- строку надо сначала найти. Политика letters_update по-прежнему разрешает
-- правку автору до срока, но letters_select больше не показывает ему
-- запечатанное - и строка становится недостижимой для обеих команд.
-- Ноль обновлённых строк, без ошибки.
--
-- Оставляем как есть: письмо в будущее, которое можно отозвать, - черновик
-- с отложенной доставкой. Настоящий отзыв возможен только служебным ключом,
-- который RLS обходит целиком, то есть требует доступа к проекту, а не
-- к приложению. Это соразмерная цена ошибки.
--
-- Записываем правду в комментарий к таблице: миграция - неизменяемый журнал,
-- и неверное утверждение в ней останется там навсегда. Пусть рядом лежит
-- то, что действительно происходит.

comment on table public.letters is
  'Письма в будущее. Запечатанное письмо не видит НИКТО, включая автора, '
  'до дня доставки. Как следствие, изменить или удалить его нельзя даже '
  'автору: UPDATE и DELETE с WHERE требуют прав на чтение, а letters_select '
  'запечатанное не показывает. Отозвать можно только служебным ключом.';

comment on column public.letters.delivered_at is
  'Проставляется, когда письмо получили ВСЕ адресаты. До этого момента '
  'строка недоступна ни на чтение, ни на изменение.';
